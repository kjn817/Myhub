-- 0066: files 소프트 삭제 (Finder 탐색기화 — 휴지통/소프트 삭제 UI의 전제)
--
-- 배경: Finder가 메모 첨부 files를 탐색기처럼 다루면서, 즉시 삭제 대신
-- deleted_at을 찍는 소프트 삭제로 전환했다. 삭제 판정은 전 경로에서
-- `deleted_at IS NULL` 조건으로 한다.
-- 운영 적용 기록 (2026-11-02): 적용 전 files 1행·deleted_at 컬럼 없음 확인
-- → 단독 적용 후 컬럼 존재·1행 유지 확인. 이 파일은 트리 정합성용
-- 재구성이며 운영 D1에는 이미 적용된 상태다 (재적용 금지).
--
-- 재구축 근거: ~/memory/2026-11-02.md의 적용 기록으로 컬럼명·대상 테이블 확정.
-- 타입(TEXT)은 이 트리의 *_at 컬럼 관례에 따른 것으로, 운영 D1 스키마
-- 대조 단계에서 최종 확정한다.
--
-- 주의: 추가형 변경만 포함한다. 운영 적용 전 Time Travel bookmark 확보 등
-- 운영 D1 안전 규칙을 따를 것.

ALTER TABLE files ADD COLUMN deleted_at TEXT;
