/**
 * 관문 테스트 22: 에러 메시지 컨텍스트
 *
 * 품질 이슈: "조회 실패" 같은 제네릭 메시지가 5곳 이상.
 * 어디서 실패했는지 알 수 없어 디버깅 어려움.
 *
 * 기대: 에러 메시지에 컨텍스트 포함 (예: "프로젝트 조회 실패", "버전 조회 실패")
 */

describe('관문 22: 에러 메시지', () => {
  test('제네릭 메시지 식별', () => {
    const genericMessages = [
      '조회 실패', // 어디를 조회?
      '생성 실패', // 뭘 생성?
      '저장 실패', // 뭘 저장?
    ]
    // 이런 메시지는 컨텍스트가 필요함
    expect(genericMessages.length).toBeGreaterThan(0)
  })

  test('개선된 메시지 예시', () => {
    const improved = {
      '조회 실패': '프로젝트 목록 조회 실패',
      '버전 없음': '요청한 버전을 찾을 수 없음',
      'Diff 실패': '버전 간 차이 계산 실패',
    }
    expect(improved['조회 실패']).toContain('프로젝트')
  })
})
